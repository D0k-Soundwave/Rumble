"""Exponential sine-sweep (ESS) measurement: sweep + inverse-filter
generation, FFT deconvolution to an impulse response, magnitude extraction,
and time gating.

Method: A. Farina, "Simultaneous Measurement of Impulse Response and
Distortion with a Swept-Sine Technique" (AES 108th Convention, 2000). The
excitation sweeps exponentially in frequency so every octave gets equal
playback time -- this (a) spreads excitation energy evenly per octave for a
usable magnitude measurement (a linear sweep would spend almost all its time
in the top octave) and (b) is what makes deconvolution separate the LINEAR
impulse response from the harmonic-distortion responses: because the sweep's
instantaneous frequency grows exponentially, a distortion product of order k
(generated by the same nonlinearity, k times the excitation's instantaneous
frequency) arrives at the matched inverse filter's output shifted to a fixed
negative-time offset -T*ln(k)/ln(f2/f1) relative to the fundamental's impulse
-- i.e. strictly *before* the true (causal) linear IR in the deconvolved
output, never after it. Taking only the causal window (from the fundamental's
arrival onward) is therefore sufficient to discard them; see `deconvolve()`.

This module owns no audio I/O -- it is pure numpy, buffers in and out, so it
is fully unit-testable with synthetic signals (the real microphone/speaker
plumbing is rumble/core/audio/mic_capture.py, wired in by a later session).
The sweep formula matches rumble/core/audio/tones.py's `generate_log_sweep`
(also cited to Farina 2000, used there for time-of-arrival correlation
instead of magnitude deconvolution) and reuses its 10 ms raised-cosine fade
convention -- see that module's `generate_sine` docstring for why 10 ms
specifically (margin above the ear's ~2-5 ms onset-detection window; not
relevant to *this* module's own math, but kept identical so a sweep played
for either purpose clicks the same, non-existent amount).

Public API:
    generate_ess       -- (sweep, inverse_filter) float32 pair, unity amplitude
    deconvolve         -- recorded audio -> causal linear impulse response
    ir_to_magnitude    -- impulse response -> (freq, dB) points on eq_math's
                          log-spaced grid
    time_gate          -- window an IR to its early (direct-sound) portion,
                          for quasi-anechoic use (S17)
    detect_first_reflection_gate_ms -- estimate a usable gate length from an
                          IR's own direct-sound peak to its first
                          significant secondary peak (S17)
    measure_rta        -- fallback measurement: average pink-noise blocks'
                          magnitude spectra, for machines where the ESS sweep
                          path misbehaves (roadmap C2)
    average_positions  -- spatially average several measurement-position
                          curves into one (roadmap C2, 3-6 mic positions)
    smooth_measurement -- octave-smooth a raw measured curve (AutoEQ's own
                          adaptive smoothing constants, via eq_target)
    agc_check          -- detect Windows mic AGC/enhancement processing by
                          comparing two same-sweep captures 6 dB apart
"""
from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np

from rumble.core import eq_math, eq_target
from rumble.core.audio import metering
from rumble.core.autoeq_merge import Point, average_curves

DEFAULT_FADE_MS = 10.0  # matches rumble/core/audio/tones.py's fade convention
DEFAULT_GATE_TAPER_MS = 1.0

# roadmap C2: "Multi-position spatial averaging for speakers (3-6 mic
# positions, average_curves() reuse)" -- a naming convention for callers
# (S13/S14's wizard), not a limit enforced by average_positions() itself.
MIN_POSITIONS = 3
MAX_POSITIONS = 6

# roadmap C1 "Mic sanity check step": "plays the same short sweep twice,
# 6 dB apart, and checks the captured level delta ~= 6 dB". 6 dB is the
# standard amplitude-halving/doubling reference step in audio engineering
# (20*log10(0.5) = -6.02 dB, rounded to the conventional 6 dB figure) --
# used because it maps onto a simple linear amplitude ratio (0.5x/2x)
# rather than an arbitrary dB value, the same reason AES17-style test
# procedures step reference levels in 6 dB increments.
AGC_STEP_DB = 6.0

# Documented allowance for measurement noise (mic self-noise, room noise,
# ADC quantization) around the expected 6 dB delta -- an explicit tolerance
# from the S12 spec, not derived from a standard.
AGC_TOLERANCE_DB = 1.5

# A captured delta below this means Windows mic "enhancement" processing
# (AGC, noise suppression) is compressing the level difference.
AGC_FLAG_THRESHOLD_DB = AGC_STEP_DB - AGC_TOLERANCE_DB  # 4.5 dB


def _raised_cosine_fade(n: int, n_fade: int) -> np.ndarray:
    """Length-n envelope of ones with raised-cosine (Hann-shaped) fade in/out
    ramps of n_fade samples at each end. Same construction as
    rumble/core/audio/tones.py's private helper of the same name -- duplicated
    rather than imported since that one is a module-private implementation
    detail there, not part of tones.py's public API.
    """
    envelope = np.ones(n, dtype=np.float64)
    if n_fade <= 0:
        return envelope
    n_fade = min(n_fade, n // 2)
    if n_fade <= 0:
        return envelope
    ramp = 0.5 * (1 - np.cos(np.pi * np.arange(n_fade) / n_fade))
    envelope[:n_fade] = ramp
    envelope[n - n_fade:] = ramp[::-1]
    return envelope


def generate_ess(
    duration_s: float,
    sample_rate: int,
    f1: float = 20.0,
    f2: float = 20000.0,
    fade_ms: float = DEFAULT_FADE_MS,
) -> tuple[np.ndarray, np.ndarray]:
    """Generate a Farina exponential sine sweep and its exact inverse filter.

    (`duration_s`/`sample_rate` are listed first, ahead of the two defaulted
    parameters, only because Python requires non-default parameters before
    defaulted ones -- f1/f2 keep the 20 Hz/20000 Hz defaults the spec calls
    for.)

    The sweep is `sin(2*pi*f1*L*(exp(t/L) - 1))` with `L = duration_s /
    ln(f2/f1)` (Farina 2000, eq. 4) -- identical formula to
    rumble/core/audio/tones.py's `generate_log_sweep`, at unity amplitude
    (callers scale/calibrate for playback; this module never touches dBFS).

    The inverse filter is the time-reversed sweep with an amplitude envelope
    `exp(-t/L)` (Farina 2000's amplitude-compensated inverse): the direct
    sweep's magnitude spectrum falls at -3 dB/octave (equal time per octave
    means equal energy per octave, and octave bandwidth in Hz doubles each
    octave, so energy density per Hz -- and hence squared magnitude -- falls
    as 1/f); reversing time keeps that same spectral shape, so multiplying
    by a *decaying* envelope in the reversed-time frame boosts the segment
    that was originally the sweep's tail (high frequencies, envelope near 1
    at reversed-time 0) relative to the segment that was originally its
    start (low frequencies, envelope near f1/f2 at reversed-time duration_s)
    -- exactly cancelling the -3 dB/octave tilt so convolving sweep*inverse
    yields a flat (frequency-independent) impulse.

    The inverse filter is then normalized so that the full linear
    convolution of `sweep` with `inverse` peaks at exactly 1.0 -- this
    self-normalization (numeric, against the actual faded/sampled sweep)
    is used instead of a closed-form scale constant so that fade shape,
    sample-rate rounding, etc. are automatically accounted for; verified
    directly by the "flat loopback recovers ~0 dB" self-test.
    """
    if f1 <= 0 or f2 <= f1:
        raise ValueError("f2 must be greater than f1 > 0")

    n = int(round(duration_s * sample_rate))
    t = np.arange(n, dtype=np.float64) / sample_rate
    L = duration_s / math.log(f2 / f1)

    sweep = np.sin(2.0 * np.pi * f1 * L * (np.exp(t / L) - 1.0))

    n_fade = int(round((fade_ms / 1000.0) * sample_rate)) if fade_ms else 0
    if n_fade > 0:
        sweep = sweep * _raised_cosine_fade(n, n_fade)

    envelope = np.exp(-t / L)
    inverse = sweep[::-1] * envelope

    conv_peak = _fft_convolve(sweep, inverse)
    peak_val = conv_peak[int(np.argmax(np.abs(conv_peak)))]
    if peak_val != 0:
        inverse = inverse / peak_val

    return sweep.astype(np.float32), inverse.astype(np.float32)


def _fft_convolve(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """Full linear convolution of `a` and `b` via zero-padded FFT (numpy
    only) -- `np.convolve` is O(len(a)*len(b)) and unusable at the sample
    counts a multi-second sweep at 48 kHz produces; this is the same method
    `deconvolve()` uses."""
    n = len(a) + len(b) - 1
    n_fft = 1 << (max(n, 1) - 1).bit_length()
    return np.fft.irfft(np.fft.rfft(a, n=n_fft) * np.fft.rfft(b, n=n_fft), n=n_fft)[:n]


def deconvolve(recorded: np.ndarray, inverse: np.ndarray, sample_rate: int) -> np.ndarray:
    """Deconvolve a `recorded` capture against the matched `inverse` filter
    from `generate_ess()`, returning the causal linear impulse response.

    Implemented as FFT-based linear convolution (numpy only: zero-padded to
    the next power of two so the circular FFT convolution matches the true
    linear convolution exactly, no `scipy.signal` dependency).

    `recorded` is assumed time-aligned so that `recorded[0]` corresponds to
    the instant the original sweep began playing (no extra lead-in/latency
    accounted for here -- that is a real-hardware play/record concern for
    the caller, same division of responsibility as
    rumble/core/time_alignment.py's `lead_in_s`).

    Because `inverse` is a matched filter built from a sweep of the same
    length, `sweep * inverse` (convolution) always peaks at a *fixed* index
    -- `len(inverse) - 1` in the full linear convolution -- regardless of
    what system's response `recorded` carries (this is the point of a
    matched inverse filter: the offset falls out of the sweep's own length,
    not the system under test). Harmonic-distortion images land at negative
    time relative to that index (see module docstring) -- i.e. strictly
    before it -- so slicing from that index onward is exactly the causal
    linear IR with distortion discarded, not an approximation.
    """
    recorded = np.asarray(recorded, dtype=np.float64)
    inverse = np.asarray(inverse, dtype=np.float64)
    full = _fft_convolve(recorded, inverse)

    ir_start = len(inverse) - 1
    return full[ir_start:].astype(np.float32)


def ir_to_magnitude(
    ir: np.ndarray,
    sample_rate: int,
    n_points: int = eq_math.GRAPH_POINTS,
) -> list[Point]:
    """Magnitude response of an impulse response, as (freq, dB) points on
    eq_math's log-spaced grid (`eq_math.frequency_array`, clamped to Nyquist).

    The IR is zero-padded to a generous minimum FFT size before transforming
    -- zero-padding only interpolates the same continuous spectrum more
    finely (no information is invented), which matters because a short,
    time-gated IR (S17) would otherwise resolve too coarsely at low
    frequencies for the requested `n_points` grid to be meaningful.
    """
    ir = np.asarray(ir, dtype=np.float64)
    n_fft = 1 << (max(len(ir), 1) - 1).bit_length()
    n_fft = max(n_fft, 1 << 16)

    spectrum = np.fft.rfft(ir, n=n_fft)
    bin_freqs = np.fft.rfftfreq(n_fft, d=1.0 / sample_rate)
    mag_db = 20.0 * np.log10(np.maximum(np.abs(spectrum), 1e-12))

    fmax = min(eq_math.GRAPH_FMAX, sample_rate / 2.0)
    freqs = eq_math.frequency_array(n_points, fmin=eq_math.GRAPH_FMIN, fmax=fmax)
    db = np.interp(freqs, bin_freqs, mag_db)
    return [(float(f), float(d)) for f, d in zip(freqs, db)]


def time_gate(
    ir: np.ndarray,
    gate_ms: float,
    sample_rate: int,
    taper_ms: float = DEFAULT_GATE_TAPER_MS,
) -> np.ndarray:
    """Window `ir` to its early, direct-sound-only portion for quasi-anechoic
    measurement (S17): keeps `gate_ms` milliseconds starting at the impulse's
    peak (the direct-sound arrival), tapering the trailing edge with a
    raised-cosine ramp of `taper_ms` (same construction as the sweep's own
    fades) to avoid the spectral leakage a hard rectangular cutoff would
    introduce. This is the standard gated-measurement technique (roadmap C4:
    quasi-anechoic above the gate's frequency limit, ~1/T_window, typically
    ~300-500 Hz domestically for a gate around 2-3 ms).

    Returns an array the same length as `ir`, zeroed outside the gated
    window, so downstream code (e.g. `ir_to_magnitude`) can treat gated and
    ungated IRs identically.
    """
    ir = np.asarray(ir, dtype=np.float64)
    peak_idx = int(np.argmax(np.abs(ir)))
    gate_samples = int(round(gate_ms / 1000.0 * sample_rate))
    taper_samples = int(round(taper_ms / 1000.0 * sample_rate))
    end = min(peak_idx + max(gate_samples, 0), len(ir))

    window = np.ones(end - peak_idx, dtype=np.float64)
    if 0 < taper_samples < len(window):
        ramp = 0.5 * (1 + np.cos(np.pi * np.arange(taper_samples) / taper_samples))
        window[-taper_samples:] = ramp

    gated = np.zeros_like(ir)
    gated[peak_idx:end] = ir[peak_idx:end] * window
    return gated.astype(np.float32)


# S17 (roadmap C4, "Spinorama-referenced estimation"): the standard
# quasi-anechoic gating technique picks the gate boundary at the earliest
# room reflection -- the direct-sound peak marks t=0, and the first
# significant secondary peak after it (in absolute value, since a wall
# reflection can invert sign) marks that boundary. _MIN_MS skips same-peak
# sidelobes right at the direct arrival; _MAX_MS is a practical ceiling
# past which a domestic room's gate choice is moot anyway (an unusually
# clean capture with no detected reflection uses this as its gate); a
# secondary peak must clear _MIN_RATIO of the direct peak's magnitude to
# count as a real reflection rather than noise floor.
_REFLECTION_SEARCH_MIN_MS = 0.5
_REFLECTION_SEARCH_MAX_MS = 15.0
_REFLECTION_MIN_RATIO = 0.15


def detect_first_reflection_gate_ms(ir: np.ndarray, sample_rate: int) -> float:
    """Estimate a usable gate length (ms), from an impulse response's own
    direct-sound peak to its first significant secondary peak -- the
    earliest room reflection, per the standard quasi-anechoic gating
    technique (roadmap C4: "gate chosen from the measured first-reflection
    arrival"). Feed the result to :func:`time_gate`.

    Falls back to :data:`_REFLECTION_SEARCH_MAX_MS` if no secondary peak
    clears :data:`_REFLECTION_MIN_RATIO` within the search window -- an
    unusually clean/anechoic-like capture should get the widest gate this
    function offers rather than a guessed arrival time.
    """
    ir = np.asarray(ir, dtype=np.float64)
    if len(ir) < 3:
        return _REFLECTION_SEARCH_MAX_MS
    peak_idx = int(np.argmax(np.abs(ir)))
    peak_val = abs(ir[peak_idx])
    if peak_val <= 0:
        return _REFLECTION_SEARCH_MAX_MS

    lo = peak_idx + int(round(_REFLECTION_SEARCH_MIN_MS / 1000.0 * sample_rate))
    hi = min(peak_idx + int(round(_REFLECTION_SEARCH_MAX_MS / 1000.0 * sample_rate)), len(ir))
    threshold = peak_val * _REFLECTION_MIN_RATIO
    for i in range(lo, hi):
        if abs(ir[i]) >= threshold:
            return (i - peak_idx) / sample_rate * 1000.0
    return _REFLECTION_SEARCH_MAX_MS


def measure_rta(
    blocks: list[np.ndarray],
    sample_rate: int,
    n_fft: int = 2048,
    n_points: int = eq_math.GRAPH_POINTS,
) -> list[Point]:
    """Fallback measurement path (roadmap C2: "pink-noise RTA averaging...
    for machines where the sweep path misbehaves"): average the magnitude
    spectrum of several already-recorded pink-noise blocks (played via
    `rumble/core/audio/tones.py`'s `generate_pink_noise` -- already a general-
    purpose generator, not Test-B-specific, so no deviation was needed there)
    onto eq_math's log-spaced grid, via `metering.spectrum_mags` per block.

    Blocks are averaged in POWER (magnitude squared), not in dB: for
    independent noise realizations, dB-domain (equivalently geometric-mean)
    averaging is a biased, downward estimator of the true average power --
    Jensen's inequality applied to the concave log function -- while power
    averaging is the unbiased estimator that the whole "average several
    blocks to reduce spectral-estimate variance" technique depends on. This
    is the standard method for estimating a spectrum from finite noisy
    records: P. Welch, "The Use of Fast Fourier Transform for the Estimation
    of Power Spectra," IEEE Trans. Audio Electroacoust., 1967.

    `n_fft` keeps `spectrum_mags`'s own general-purpose default (2048)
    rather than the 8192 `rumble/ui/spectrum_overlay.py` derives for its own
    latency/resolution constraints (see that function's docstring) -- this
    fallback path has no such constraint of its own yet; a real-mic caller
    (S13) should pass an explicit `n_fft` once its block size/latency budget
    is known.
    """
    if not blocks:
        return []

    freqs_hz: np.ndarray | None = None
    power_sum: np.ndarray | None = None
    for block in blocks:
        block_freqs, mags_db = metering.spectrum_mags(
            np.asarray(block, dtype=np.float64), sample_rate, n_fft=n_fft
        )
        freqs_hz = block_freqs
        # mags_db is already floored at metering.FLOOR_DBFS (never -inf), so
        # 10**(mags_db/20) is bounded away from 0 -- no extra epsilon needed
        # before the log10 below.
        power = (10.0 ** (mags_db / 20.0)) ** 2
        power_sum = power if power_sum is None else power_sum + power

    avg_power = power_sum / len(blocks)
    avg_mag_db = 10.0 * np.log10(avg_power)

    fmax = min(eq_math.GRAPH_FMAX, sample_rate / 2.0)
    out_freqs = eq_math.frequency_array(n_points, fmin=eq_math.GRAPH_FMIN, fmax=fmax)
    db = np.interp(out_freqs, freqs_hz, avg_mag_db)
    return [(float(f), float(d)) for f, d in zip(out_freqs, db)]


def average_positions(curves: list[list[Point]]) -> list[Point]:
    """Spatially average measurements taken at multiple mic positions into a
    single representative curve.

    Thin wrapper around `autoeq_merge.average_curves` (unweighted average on
    the curves' reconciled common grid) -- the DSP is identical to AutoEQ's
    own multi-measurement averaging, just applied to acoustic measurement
    positions instead of published headphone-unit variance. Roadmap C2:
    "Multi-position spatial averaging for speakers (3-6 mic positions,
    average_curves() reuse)" -- `MIN_POSITIONS`/`MAX_POSITIONS` name that
    convention for callers (S13/S14's wizard); this function itself averages
    however many curves it is given.
    """
    return average_curves(curves)


def smooth_measurement(curve: list[Point]) -> list[Point]:
    """Octave-smooth a raw measured curve using AutoEQ's own adaptive
    smoothing constants (`eq_target.octave_smooth_adaptive`: a narrow window
    at low frequencies, preserving real modal detail, widening through the
    treble transition band). Roadmap C3's correction pipeline applies the
    same smoothing to auto-generated targets, so a measured curve fed
    through this stays on a consistent basis with the rest of the pipeline.
    """
    return eq_target.octave_smooth_adaptive(curve)


@dataclass
class AgcCheckResult:
    delta_db: float
    processing_detected: bool


def agc_check(
    record_fn,
    duration_s: float = 1.0,
    sample_rate: int = 48000,
) -> AgcCheckResult:
    """Mic sanity check (roadmap C1): play/record the SAME short sweep
    twice, the second `AGC_STEP_DB` (6 dB) quieter, and compare the captured
    level delta. Windows capture "enhancements" (AGC, noise suppression,
    beamforming) actively corrupt measurements and can't be reliably
    disabled programmatically -- a delta compressed below
    `AGC_FLAG_THRESHOLD_DB` means such processing is active, and the caller
    (S13's wizard) should walk the user through disabling it before
    continuing (detect-and-instruct, the A1 pattern).

    `record_fn(signal, sample_rate) -> recorded_array` is the injectable
    play+record callable -- this module owns no audio I/O (see the module
    docstring), so S13 wires `record_fn` to the real play/`MicRecorder`
    path while tests fake it directly (e.g. simulating a compressor by
    scaling the returned signal's level).
    """
    sweep, _ = generate_ess(duration_s, sample_rate)
    quiet_sweep = sweep * (10.0 ** (-AGC_STEP_DB / 20.0))

    recorded_ref = np.asarray(record_fn(sweep, sample_rate), dtype=np.float64)
    recorded_quiet = np.asarray(record_fn(quiet_sweep, sample_rate), dtype=np.float64)

    level_ref = metering.rms_dbfs(recorded_ref)
    level_quiet = metering.rms_dbfs(recorded_quiet)
    delta_db = level_ref - level_quiet

    return AgcCheckResult(
        delta_db=delta_db,
        processing_detected=delta_db < AGC_FLAG_THRESHOLD_DB,
    )
